CREATE TABLE ballot_reviews (
 id CHAR(36) PRIMARY KEY, vote_id CHAR(36) NOT NULL, actor_id CHAR(36) NOT NULL,
 reason VARCHAR(1000) NOT NULL, valid BOOLEAN NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), FOREIGN KEY(vote_id) REFERENCES votes(id), FOREIGN KEY(actor_id) REFERENCES admins(id)
) ENGINE=InnoDB;
